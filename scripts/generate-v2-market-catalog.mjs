import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MODULE_PATH = resolve(ROOT, "src/v2/markets/catalog.js");
const JSON_PATH = resolve(ROOT, "public/data/v2-markets.json");
const VERSION = "2026-08-06";
const PINNED_LOCATION_CODES = [2840, 2826, 2124, 2036, 2682, 2784, 2702, 2356];

function validateCatalog(snapshot) {
  if (snapshot?.version !== VERSION || !Array.isArray(snapshot.locations) || !Array.isArray(snapshot.languages)) {
    throw new Error("Invalid canonical market catalog.");
  }
  const locationCodes = new Set(snapshot.locations.map((item) => item.location_code));
  for (const code of PINNED_LOCATION_CODES) {
    if (!locationCodes.has(code)) throw new Error(`Missing pinned location ${code}.`);
  }
  return { locations: snapshot.locations, languages: snapshot.languages };
}

function catalogModule({ locations, languages }) {
  const rows = locations.map((location) => [
    location.location_code,
    location.country_iso_code,
    location.location_name,
    location.location_type,
    location.supported_language_codes,
  ]);
  const languageRows = languages.map((language) => [language.language_code, language.language_name]);

  return `/**
 * Generated by scripts/generate-v2-market-catalog.mjs from the reviewed,
 * canonical public market catalog. Do not edit by hand.
 */
export const MARKET_CATALOG_VERSION = ${JSON.stringify(VERSION)};

const COUNTRY_ROWS = ${JSON.stringify(rows, null, 2)};
const LANGUAGE_ROWS = ${JSON.stringify(languageRows, null, 2)};
const PINNED_LOCATION_CODES = Object.freeze(${JSON.stringify(PINNED_LOCATION_CODES)});

function frozenRecord(record) {
  return Object.freeze(record);
}

function normalizeLanguageCode(code) {
  return String(code ?? "").trim().toLowerCase();
}

export const LOCATIONS = Object.freeze(COUNTRY_ROWS.map(([
  location_code,
  country_iso_code,
  location_name,
  location_type,
  supported_language_codes,
]) => frozenRecord({
  location_code,
  country_iso_code,
  location_name,
  location_type,
  supported_language_codes: Object.freeze([...supported_language_codes]),
})));

export const LANGUAGES = Object.freeze(LANGUAGE_ROWS.map(([language_code, language_name]) => frozenRecord({
  language_code,
  language_name,
})));

const LOCATIONS_BY_CODE = new Map(LOCATIONS.map((location) => [location.location_code, location]));
const LANGUAGES_BY_CODE = new Map(LANGUAGES.map((language) => [
  normalizeLanguageCode(language.language_code),
  language,
]));

export function findLocation(code) {
  return LOCATIONS_BY_CODE.get(Number(code)) ?? null;
}

export function findLanguage(code) {
  return LANGUAGES_BY_CODE.get(normalizeLanguageCode(code)) ?? null;
}

export function isSupportedMarket(locationCode, languageCode) {
  const location = findLocation(locationCode);
  const language = findLanguage(languageCode);
  return Boolean(location && language && location.supported_language_codes.includes(language.language_code));
}

export function pinnedLocations() {
  return Object.freeze(PINNED_LOCATION_CODES.map((code) => findLocation(code)));
}
`;
}

function catalogJson({ locations, languages }) {
  return `${JSON.stringify({
    version: VERSION,
    locations,
    languages,
    pinned_location_codes: PINNED_LOCATION_CODES,
  }, null, 2)}\n`;
}

const snapshot = validateCatalog(JSON.parse(await readFile(JSON_PATH, "utf8")));
const generatedFiles = new Map([
  [MODULE_PATH, catalogModule(snapshot)],
]);
const checkOnly = process.argv.slice(2).includes("--check");
const unknownArguments = process.argv.slice(2).filter((argument) => argument !== "--check");

if (unknownArguments.length) {
  throw new Error(`Unknown argument(s): ${unknownArguments.join(", ")}`);
}

if (checkOnly) {
  const staleFiles = [];
  for (const [path, content] of generatedFiles) {
    if (await readFile(path, "utf8") !== content) staleFiles.push(path);
  }
  if (staleFiles.length) {
    throw new Error(`Generated market catalog is stale: ${staleFiles.join(", ")}`);
  }
} else {
  await Promise.all([...generatedFiles].map(([path, content]) => writeFile(path, content)));
}
